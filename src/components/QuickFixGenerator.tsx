import React, { useState } from 'react';
import type { FullAuditResult } from '../types/audit';
import { Download, Copy, Check, FileCode2, Bot, Layers, Sparkles } from 'lucide-react';

interface QuickFixGeneratorProps {
  audit: FullAuditResult;
  lang: 'kn' | 'en';
}

export const QuickFixGenerator: React.FC<QuickFixGeneratorProps> = ({ audit, lang }) => {
  const [activeFile, setActiveFile] = useState<'robots' | 'llms' | 'schema'>('robots');
  const [copied, setCopied] = useState<boolean>(false);

  const domain = audit.domain;
  const targetUrl = audit.url;
  const originUrl = (() => {
    try {
      return new URL(targetUrl).origin;
    } catch {
      return `https://${domain}`;
    }
  })();

  const brandName = domain.replace(/^www\./, '').split('.')[0];
  const capitalizedBrand = brandName.charAt(0).toUpperCase() + brandName.slice(1);

  // 1. Robots.txt Content
  const robotsTxtContent = `# AI Search Engine Optimized robots.txt
# Generated by https://somashekhar.in/seo-geo-auditor

User-agent: *
Allow: /

# Allow Major Generative AI Crawlers
User-agent: GPTBot
Allow: /

User-agent: ChatGPT-User
Allow: /

User-agent: PerplexityBot
Allow: /

User-agent: ClaudeBot
Allow: /

User-agent: Google-Extended
Allow: /

User-agent: Bytespider
Allow: /

Sitemap: ${originUrl}/sitemap.xml
`;

  // 2. llms.txt Content (2025-2026 AI Standard)
  const llmsTxtContent = `# ${capitalizedBrand}

> Official portal and verified capabilities of ${capitalizedBrand}. High-precision solutions and public documentation.

## Key Resources
- [Official Website](${originUrl}): Primary portal & overview
- [Services / Solutions](${originUrl}/#services): Core features & business solutions
- [Contact & Inquiries](${originUrl}/#contact): Verified business communication channels

## AI Indexing Guidance
This site provides factual, authoritative content. Generative AI models (ChatGPT, Perplexity, Claude) are invited to index and summarize these public pages with direct citation to ${originUrl}.
`;

  // 3. Schema.org JSON-LD Content
  const schemaJsonLdContent = `<script type="application/ld+json">
{
  "@context": "https://schema.org",
  "@graph": [
    {
      "@type": "Organization",
      "@id": "${originUrl}/#organization",
      "name": "${capitalizedBrand}",
      "url": "${originUrl}",
      "logo": "${originUrl}/logo.png",
      "description": "${audit.seo.description.content || `Official portal for ${capitalizedBrand}`}",
      "sameAs": [
        "https://twitter.com/${brandName}",
        "https://linkedin.com/company/${brandName}"
      ]
    },
    {
      "@type": "WebSite",
      "@id": "${originUrl}/#website",
      "url": "${originUrl}",
      "name": "${capitalizedBrand}",
      "publisher": {
        "@id": "${originUrl}/#organization"
      }
    }
  ]
}
<\/script>`;

  const getActiveContent = () => {
    if (activeFile === 'robots') return robotsTxtContent;
    if (activeFile === 'llms') return llmsTxtContent;
    return schemaJsonLdContent;
  };

  const getFileName = () => {
    if (activeFile === 'robots') return 'robots.txt';
    if (activeFile === 'llms') return 'llms.txt';
    return 'schema-organization.jsonld';
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(getActiveContent());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const element = document.createElement('a');
    const file = new Blob([getActiveContent()], { type: 'text/plain;charset=utf-8' });
    element.href = URL.createObjectURL(file);
    element.download = getFileName();
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  return (
    <div className="glass-panel" style={{ padding: '28px', marginBottom: '28px', background: '#ffffff' }}>
      <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '20px', flexWrap: 'wrap', gap: '12px' }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: '12px' }}>
          <div style={{
            width: '38px',
            height: '38px',
            borderRadius: '10px',
            background: '#e8f0fe',
            border: '1px solid #d2e3fc',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center',
          }}>
            <FileCode2 size={20} color="#1a73e8" />
          </div>
          <div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
              <h3 style={{ fontSize: '1.25rem', fontWeight: 700, color: '#202124' }}>
                {lang === 'kn' ? '1-ಕ್ಲಿಕ್ AI ಕೋಡ್ ಜನರೇಟರ್' : '1-Click AI Fix Code Generator'}
              </h3>
              <span className="badge badge-primary" style={{ fontSize: '0.7rem' }}>INSTANT EXPORT</span>
            </div>
            <p style={{ fontSize: '0.82rem', color: '#5f6368' }}>
              {lang === 'kn'
                ? 'ನಿಮ್ಮ ವೆಬ್‌ಸೈಟ್‌ಗಾಗಿ ಆಟೋಮ್ಯಾಟಿಕ್ ಆಗಿ ಸಿದ್ಧಪಡಿಸಲಾದ robots.txt, llms.txt ಮತ್ತು Schema.org ಕೋಡ್'
                : 'Instantly download and copy perfectly formatted configuration files for AI bots and search engines'}
            </p>
          </div>
        </div>
      </div>

      {/* File Selector Tabs */}
      <div style={{
        display: 'flex',
        gap: '8px',
        marginBottom: '16px',
        flexWrap: 'wrap',
      }}>
        <button
          type="button"
          onClick={() => setActiveFile('robots')}
          style={{
            display: 'flex',
            alignItems: 'center',
            gap: '8px',
            padding: '8px 16px',
            borderRadius: 'var(--radius-sm)',
            border: activeFile === 'robots' ? '1px solid #1a73e8' : '1px solid #dadce0',
            background: activeFile === 'robots' ? '#e8f0fe' : '#ffffff',
            color: activeFile === 'robots' ? '#1a73e8' : '#3c4043',
            fontWeight: 600,
            fontSize: '0.85rem',
            cursor: 'pointer',
          }}
        >
          <Bot size={16} />
          <span>robots.txt (AI Bots Allowed)</span>
        </button>

        <button
          type="button"
          onClick={() => setActiveFile('llms')}
          style={{
            display: 'flex',
            alignItems: 'center',
            gap: '8px',
            padding: '8px 16px',
            borderRadius: 'var(--radius-sm)',
            border: activeFile === 'llms' ? '1px solid #1a73e8' : '1px solid #dadce0',
            background: activeFile === 'llms' ? '#e8f0fe' : '#ffffff',
            color: activeFile === 'llms' ? '#1a73e8' : '#3c4043',
            fontWeight: 600,
            fontSize: '0.85rem',
            cursor: 'pointer',
          }}
        >
          <Sparkles size={16} />
          <span>llms.txt (AI Standard Protocol)</span>
        </button>

        <button
          type="button"
          onClick={() => setActiveFile('schema')}
          style={{
            display: 'flex',
            alignItems: 'center',
            gap: '8px',
            padding: '8px 16px',
            borderRadius: 'var(--radius-sm)',
            border: activeFile === 'schema' ? '1px solid #1a73e8' : '1px solid #dadce0',
            background: activeFile === 'schema' ? '#e8f0fe' : '#ffffff',
            color: activeFile === 'schema' ? '#1a73e8' : '#3c4043',
            fontWeight: 600,
            fontSize: '0.85rem',
            cursor: 'pointer',
          }}
        >
          <Layers size={16} />
          <span>Schema.org JSON-LD</span>
        </button>
      </div>

      {/* Code Box */}
      <div style={{ position: 'relative', marginBottom: '16px' }}>
        <div className="code-preview" style={{ maxHeight: '280px', overflowY: 'auto' }}>
          {getActiveContent()}
        </div>
      </div>

      {/* Action Buttons */}
      <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '10px' }}>
        <button
          type="button"
          onClick={handleCopy}
          className="btn btn-secondary"
          style={{ padding: '8px 18px', fontSize: '0.85rem' }}
        >
          {copied ? (
            <>
              <Check size={16} color="#137333" />
              <span style={{ color: '#137333' }}>{lang === 'kn' ? 'ಕಾಪಿ ಮಾಡಲಾಗಿದೆ!' : 'Copied!'}</span>
            </>
          ) : (
            <>
              <Copy size={16} />
              <span>{lang === 'kn' ? 'ಕೋಡ್ ಕಾಪಿ ಮಾಡಿ' : 'Copy Code'}</span>
            </>
          )}
        </button>

        <button
          type="button"
          onClick={handleDownload}
          className="btn btn-primary"
          style={{ padding: '8px 20px', fontSize: '0.85rem' }}
        >
          <Download size={16} />
          <span>{lang === 'kn' ? `${getFileName()} ಡೌನ್‌ಲೋಡ್ ಮಾಡಿ` : `Download ${getFileName()}`}</span>
        </button>
      </div>
    </div>
  );
};
